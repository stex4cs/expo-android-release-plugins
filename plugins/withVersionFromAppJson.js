const { withAppBuildGradle } = require('expo/config-plugins');

// Make android/app/build.gradle read the version out of app.json.
//
// Prebuild writes versionCode into build.gradle as a literal, from whatever
// app.json said at the time. That is fine when every build goes through
// prebuild -- but we build locally with gradle far more often than we run it,
// so the literal goes stale the moment the version is bumped.
//
// It had: app.json said 6 while build.gradle still said 4, three bumps behind.
// A local build would have shipped 4, and Play rejects a versionCode it has
// already seen without explaining itself.
//
// This uses withAppBuildGradle rather than withDangerousMod on purpose. A
// dangerous mod runs before Expo's own version mod, which then writes the
// literal back over it -- tried that first, and versionCode came out hardcoded
// while versionName survived, which is exactly the fingerprint of being
// overwritten by a later mod. withAppBuildGradle runs in the ordinary chain,
// after Expo has had its say.
//
// android/ is regenerated by prebuild, so this lives in a plugin rather than a
// hand edit -- the same reason as withProguardRules.

const MARKER = 'Added by plugins/withVersionFromAppJson.js';

const READER = `
    // ${MARKER}
    // app.json is the single source for the version; see the plugin for why.
    def appJson = new groovy.json.JsonSlurper().parse(rootProject.file('../app.json'))
`;

module.exports = function withVersionFromAppJson(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') return cfg;

    let src = cfg.modResults.contents;

    // The reader goes just inside `android {`, ahead of defaultConfig using it.
    if (!src.includes(MARKER)) {
      src = src.replace(/\n(\s*)defaultConfig\s*\{/, `\n${READER}\n$1defaultConfig {`);
    }

    // Swap the literals Expo wrote for the values read at configuration time.
    // Every run, not just the first: a prebuild over an existing android/ runs
    // Expo's version mod again, and it rewrites `versionCode <expression>` back
    // into a literal (seen 14.10: `versionCode 7` with the reader still there).
    src = src.replace(
      /versionCode\s+\d+/,
      'versionCode appJson.expo.android.versionCode'
    );
    src = src.replace(
      /versionName\s+"[^"]*"/,
      'versionName appJson.expo.version'
    );

    cfg.modResults.contents = src;
    return cfg;
  });
};
